//! L2 → L3: structured, evidence-checked claims about what happened.
//!
//! INTERFACE (frozen for parallel work; the implementation fills the bodies):
//! - [`build_packet`] turns a compiled window into a bounded evidence packet.
//!   Restricted evidence never enters a packet unredacted.
//! - [`interpret`] runs the model through a [`Provider`] and returns an [`Interpretation`].
//! - [`check`] validates output against its packet outside the prompt. Failing items are
//!   dropped or downgraded, never silently kept.

use chrono::{DateTime, Utc};
use hx_compile::{EvidenceId, Timeline};
use hx_schema::Interval;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct EvidenceItem {
    pub id: EvidenceId,
    pub at: DateTime<Utc>,
    pub kind: String,
    /// Redacted, size-capped text the model may read.
    pub text: String,
    /// Generated by Hyperthymesia itself (never independent corroboration).
    pub self_generated: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Packet {
    pub window: Interval,
    /// Compact rendering of lanes, coverage and points for the prompt.
    pub timeline_text: String,
    pub evidence: Vec<EvidenceItem>,
    /// Entity memory snapshot (projects, repos, people) as provenance-backed lines.
    pub entities: Vec<String>,
    /// Tasks still open at the end of the previous window.
    pub open_tasks: Vec<Task>,
    pub input_digest: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Basis {
    Observed,
    ReportedBySource,
    Inferred,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Claim {
    pub actor: String,
    pub action: String,
    pub object: String,
    /// `completed`, `attempted`, `unknown`. Completion requires outcome evidence.
    pub outcome: String,
    pub basis: Basis,
    pub evidence: Vec<EvidenceId>,
    #[serde(default)]
    pub outcome_evidence: Vec<EvidenceId>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Episode {
    pub id: String,
    pub intervals: Vec<Interval>,
    pub title: String,
    pub description: String,
    pub claims: Vec<Claim>,
    pub evidence: Vec<EvidenceId>,
    pub confidence: f32,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Task {
    /// Stable across windows; merges and splits keep aliases.
    pub id: String,
    pub title: String,
    pub description: String,
    /// Disjoint interval set (interleaving allowed).
    pub intervals: Vec<Interval>,
    pub episode_ids: Vec<String>,
    #[serde(default)]
    pub goal: Option<String>,
    #[serde(default)]
    pub aliases: Vec<String>,
    pub confidence: f32,
    /// Still ongoing at the end of the window.
    pub open: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Interpretation {
    pub window: Interval,
    pub episodes: Vec<Episode>,
    pub tasks: Vec<Task>,
    pub summary: String,
    pub provenance: Provenance,
    /// Items removed or downgraded by [`check`], kept for audit.
    pub check_failures: Vec<CheckFailure>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Provenance {
    pub input_digest: String,
    pub compiler_version: String,
    pub prompt_version: String,
    pub model: String,
    pub created_at: DateTime<Utc>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CheckFailure {
    pub item: String,
    pub reason: String,
}

#[derive(Debug, thiserror::Error)]
pub enum InterpretError {
    #[error("provider failed: {0}")]
    Provider(String),
    #[error("model output did not parse after retries: {0}")]
    Parse(String),
}

/// A language model backend. Implementations: Claude CLI (`claude -p`), recorded fixtures.
pub trait Provider: Send + Sync {
    fn name(&self) -> String;
    fn complete(
        &self,
        system: &str,
        user: &str,
    ) -> impl std::future::Future<Output = Result<String, InterpretError>> + Send;
}

pub const PROMPT_VERSION: &str = "interpret/v1";

pub fn build_packet(
    timeline: &Timeline,
    evidence: &[EvidenceItem],
    entities: &[String],
    open_tasks: &[Task],
) -> Packet {
    Packet {
        window: timeline.window,
        timeline_text: String::new(),
        evidence: evidence.to_vec(),
        entities: entities.to_vec(),
        open_tasks: open_tasks.to_vec(),
        input_digest: String::new(),
    }
}

pub async fn interpret<P: Provider>(
    packet: &Packet,
    provider: &P,
) -> Result<Interpretation, InterpretError> {
    let _ = (packet, provider);
    Err(InterpretError::Provider("not implemented".into()))
}

pub fn check(interpretation: &Interpretation, packet: &Packet) -> Vec<CheckFailure> {
    let _ = (interpretation, packet);
    vec![]
}
