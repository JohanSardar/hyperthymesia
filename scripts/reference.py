#!/usr/bin/env python3
"""Generate or check references against built CLIs and current source, without owner state."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/reference"
BINS = ["hx-server", "hx-move"] + [
    "hx-connector-" + name for name in ("apple-bridge", "claude-code", "codex", "git", "t3code")
]
HEADER = "<!-- Generated by scripts/reference.py; edit source and regenerate. -->\n\n"

def env_names(code):
    names = set(re.findall(
        r'"((?:HX_|HYPERTHYMESIA_|FX_)[A-Z0-9_]+|AI_GATEWAY_API_KEY|RUST_LOG)"', code))
    names.update(re.findall(r'\b(?:var|var_os|env|env_remove)\(\s*"([A-Z][A-Z0-9_]+)"', code))
    return {key for key in names if not re.search(r"TEST|E2E|SYNTHETIC", key)}


def balanced(text, start, opener="(", closer=")"):
    depth, quoted, escaped = 0, False, False
    for index in range(start, len(text)):
        char = text[index]
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
        elif char == '"':
            quoted = True
        elif char == opener:
            depth += 1
        elif char == closer:
            depth -= 1
            if depth == 0:
                return text[start:index + 1]
    raise ValueError("unbalanced source expression")


def generated():
    target = Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target"))
    if not target.is_absolute():
        target = ROOT / target
    build = ["cargo", "build", "--locked", "--workspace"]
    if sys.platform != "darwin":
        for package in ("hx-macos-sys", "hx-agent", "hx-agent-app"):
            build += ["--exclude", package]
    subprocess.run(build, cwd=ROOT, check=True)
    subprocess.run(["cargo", "build", "--locked", "-p", "hx-server",
                    "--example", "export-reference"], cwd=ROOT, check=True)
    pages = {}
    with tempfile.TemporaryDirectory(prefix="hx-reference-") as home:
        env = {"HOME": home, "PATH": os.environ["PATH"], "NO_COLOR": "1",
               "COLUMNS": "100", "HX_HOST_BASH": "on"}
        cli = HEADER + "# Command and option reference\n\n"
        cli += "Captured from every public command's real `--help` with an empty HOME/environment.\n"
        cli += "Installer-only server commands are included separately; do not invoke them manually.\n\n"
        for binary in BINS:
            queue, seen = [()], set()
            if binary == "hx-server":
                source = (ROOT / "crates/hx-server/src/main.rs").read_text()
                hidden = re.findall(r"#\[command\(hide = true\)\]\s+(\w+)", source)
                queue += [(re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower(),) for name in hidden]
            while queue:
                command = queue.pop(0)
                if command in seen:
                    continue
                seen.add(command)
                help_text = subprocess.check_output(
                    [str(target / "debug" / binary), *command, "--help"],
                    env=env, cwd=home, text=True, timeout=10,
                )
                help_text = "\n".join(line.rstrip() for line in help_text.splitlines())
                name = " ".join([binary, *command])
                cli += "## " + name + "\n\n```text\n" + help_text.rstrip() + "\n```\n\n"
                section = help_text.split("Commands:\n", 1)
                if len(section) == 2:
                    for child in re.findall(r"(?m)^  ([a-z][a-z0-9-]*)\s", section[1].split("Options:", 1)[0]):
                        if child != "help":
                            queue.append((*command, child))
        pages["cli.md"] = cli.rstrip() + "\n"
        schemas = subprocess.check_output(
            [str(target / "debug/examples/export-reference")], env=env, cwd=home, timeout=10)
        pages["mcp-tools.json"] = json.dumps(json.loads(schemas), indent=2, sort_keys=True) + "\n"

    agent = (ROOT / "crates/hx-agent/src/main.rs").read_text()
    declarations = agent[agent.index("#[derive(Parser)]"):agent.index("fn main()")]
    pages["macos.md"] = HEADER + """# macOS command surface

`hx-agent` is built from source on macOS. The declaration below is the exact
command/option surface. `--help` is safe; `onboard` requests permissions and
`run` can capture activity. Never run those unattended on someone else's Mac.

`hx-agent-app` is a menu-bar application, not a CLI with options. Use its menu
to pair, grant permissions, pause or quit. The installer never launches it.
The separate `e2e-harness` build cannot request permissions or build in release.

```rust
""" + declarations.rstrip() + "\n```\n"
    routes = HEADER + "# HTTP route inventory\n\n"
    routes += "All public route registrations, including dashboard forms. See [API contracts](api.md).\n\n"
    routes += "| Method | Path | Implementation |\n| --- | --- | --- |\n"
    for name in ("lib", "sources", "connection_api", "mcp"):
        path = ROOT / f"crates/hx-server/src/{name}.rs"
        text = path.read_text()
        for match in re.finditer(r'\.route\(\s*"([^"]+)"\s*,', text):
            expr = balanced(text, text.index("(", match.start()))
            line = text[:match.start()].count("\n") + 1
            methods = re.findall(r"\b(get|post|put|patch|delete)\(", expr)
            for method in methods:
                routes += f"| {method.upper()} | `{match[1]}` | [{name}.rs:{line}](../../crates/hx-server/src/{name}.rs#L{line}) |\n"
    pages["routes.md"] = routes
    settings = {"RUST_LOG": {"crates/hx-server/src/main.rs"}}
    for path in sorted([*ROOT.glob("crates/*/src/**/*.rs"), *ROOT.glob("connectors/*/src/**/*.rs")]):
        if path.stem == "tests" or path.stem.endswith("_tests"):
            continue
        code = re.split(r"(?m)^#\[cfg\(test\)\]\nmod \w+ \{", path.read_text())[0]
        for key in env_names(code):
            settings.setdefault(key, set()).add(path.relative_to(ROOT).as_posix())
    for name in ("scripts/install.sh", "docs/install"):
        path = ROOT / name
        if path.exists():
            for key in re.findall(r"\b(?:HX_|FX_)[A-Z0-9_]+\b", path.read_text()):
                settings.setdefault(key, set()).add(name)
    text = HEADER + "# Environment variable inventory\n\n"
    text += "Production variable names and their implementation references. See [configuration](configuration.md) for defaults and security semantics.\n\n"
    text += "| Name | Defined/read in |\n| --- | --- |\n"
    for key, paths in sorted(settings.items()):
        links = ", ".join(f"[{p}](../../{p})" for p in sorted(paths))
        text += f"| `{key}` | {links} |\n"
    pages["environment.md"] = text
    return pages


def check_links():
    files = [ROOT / "README.md", *ROOT.glob("*.md"), *ROOT.glob("docs/**/*.md"),
             *ROOT.glob("crates/*/README.md"), *ROOT.glob("companions/*/README.md")]
    for path in set(files):
        for link in re.findall(r"(?<!!)\[[^\]]*\]\(([^)]+)\)", path.read_text()):
            if re.match(r"[a-z]+:|#", link):
                continue
            destination = unquote(link.split("#", 1)[0])
            if destination and not (path.parent / destination).exists():
                raise SystemExit(f"Broken local link: {path.relative_to(ROOT)} -> {destination}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, contents in generated().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Reference drift: {path.relative_to(ROOT)}; run python3 scripts/reference.py")
        else:
            path.write_text(contents)
    check_links()
    print("ok: CLI, macOS declarations, MCP schemas, routes, settings and local links")


if __name__ == "__main__":
    main()
